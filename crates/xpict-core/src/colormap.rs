/// Sample the named colormap (default: xenosite). `z` in [0,1] sequential,
/// or pass `diverging=true` to remap [-1,1] → [0,1] first.
pub fn sample_colormap(z: f64, diverging: bool) -> [f64; 3] {
    let t = if diverging { ((z + 1.0) * 0.5).clamp(0.0, 1.0) } else { z.clamp(0.0, 1.0) };
    let n = XENOSITE.len();
    if n == 1 { return XENOSITE[0]; }
    let x = t * (n - 1) as f64;
    let i = (x as usize).min(n - 2);
    let f = x - i as f64;
    let a = XENOSITE[i];
    let b = XENOSITE[i + 1];
    [
        a[0] + (b[0] - a[0]) * f,
        a[1] + (b[1] - a[1]) * f,
        a[2] + (b[2] - a[2]) * f,
    ]
}

/// CSS `rgb(r,g,b)` for a shade stop.
pub fn colormap_rgb(z: f64, diverging: bool) -> String {
    let [r, g, b] = sample_colormap(z, diverging);
    format!(
        "rgb({},{},{})",
        (r * 255.0 + 0.5) as i32,
        (g * 255.0 + 0.5) as i32,
        (b * 255.0 + 0.5) as i32
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn xenosite_ends() {
        assert_eq!(sample_colormap(0.0, false), [1.0, 1.0, 1.0]);
        let hot = sample_colormap(1.0, false);
        assert!(hot[0] > 0.9 && hot[1] < 0.4 && hot[2] < 0.1);
    }
    #[test]
    fn mid_is_greenish() {
        let [r, g, b] = sample_colormap(0.5, false);
        assert!(g > r && g > b);
    }
}
