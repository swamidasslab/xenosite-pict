/** Element symbol for atomic number `z`. Unknown → `"X"`. */
export function elementSymbol(z: number): string {
  if (!Number.isFinite(z) || z < 0) return "X";
  return SYMBOLS[z | 0] ?? "X";
}

/** Atomic number for a symbol (case-insensitive). `"*"` / `"R"` → `0`. */
export function atomicNumber(symbol: string): number | undefined {
  const s = symbol.trim();
  if (!s) return undefined;
  if (s === "*" || s.toUpperCase() === "R") return 0;
  const lower = s.toLowerCase();
  for (let z = 1; z < SYMBOLS.length; z++) {
    if (SYMBOLS[z]!.toLowerCase() === lower) return z;
  }
  return undefined;
}
